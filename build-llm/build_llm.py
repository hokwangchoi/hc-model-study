def person(p):
    name, pron, town, pet, pet_name, job, color = p
    return dict(name=name, pron=pron, Pron=pron.capitalize(), town=town, pet=pet, pet_name=pet_name,
                job=job, color=color, action=PET_ACTION[pet])


def make_corpus(n_docs=4000, seed=0):
    """Return short documents: fact sheets (35%), Q&A notes (15%) and little stories (50%)."""
    rng = random.Random(seed)
    docs = []
    for _ in range(n_docs):
        p = person(rng.choice(PEOPLE))
        r = rng.random()
        if r < 0.35:
            facts = rng.sample(FACTS, k=rng.randint(3, len(FACTS)))
            docs.append(" ".join(f.format(**p) for f in facts))
        elif r < 0.5:  # web text is full of FAQ-like pages; this is where "answering" is first learned
            qas = rng.sample(QUESTIONS, k=rng.randint(2, len(QUESTIONS)))
            docs.append(" ".join(f"{q} {a}".format(**p) for q, a in qas))
        else:
            friend = person(rng.choice([q for q in PEOPLE if q[0] != p["name"]]))
            slots = dict(p, friend=friend["name"], ftown=friend["town"], **{k: rng.choice(v) for k, v in WORDS.items()})
            sents = [rng.choice(OPENERS)] + rng.sample(MIDDLES, k=rng.randint(2, 3)) + [rng.choice(ENDINGS)]
            docs.append(" ".join(s.format(**slots) for s in sents))
    return docs


# =====================================================================================
# 2. TOKENIZER - byte-level BPE, trained from scratch.
#    Start from the 256 byte values (so ANY string round-trips), then repeatedly merge
#    the most frequent adjacent pair into a new token.
# =====================================================================================

# GPT-2-style pre-tokenizer: split into words with their leading space, numbers, punctuation,
# whitespace. Merges never cross these chunk boundaries.
PRETOKENIZE = re.compile(r"""'s|'t|'re|'ve|'m|'ll|'d| ?[A-Za-z]+| ?[0-9]+| ?[^\sA-Za-z0-9]+|\s+(?!\S)|\s+""")
SPECIALS = ["<|endoftext|>", "<|user|>", "<|assistant|>", "<|end|>"]


def merge_pair(ids, pair, new_id):
    out, i = [], 0
    while i < len(ids):
        if i + 1 < len(ids) and ids[i] == pair[0] and ids[i + 1] == pair[1]:
            out.append(new_id)
            i += 2
        else:
            out.append(ids[i])
            i += 1
    return out


class BPETokenizer:
    def __init__(self, merges=()):
        self.merges = [tuple(m) for m in merges]  # merges[i] = (a, b) -> new id 256 + i
        self.ranks = {m: i for i, m in enumerate(self.merges)}
        self.vocab = {i: bytes([i]) for i in range(256)}
        for i, (a, b) in enumerate(self.merges):
            self.vocab[256 + i] = self.vocab[a] + self.vocab[b]
        base = 256 + len(self.merges)
        self.special_ids = {s: base + i for i, s in enumerate(SPECIALS)}
        self.id_to_special = {v: k for k, v in self.special_ids.items()}
        self._split = re.compile("(" + "|".join(re.escape(s) for s in SPECIALS) + ")")
        self._cache = {}

    @property
    def vocab_size(self):
        return 256 + len(self.merges) + len(SPECIALS)

    @staticmethod
    def train(text, vocab_size, verbose=0):
        """Train on word *counts*: each distinct pre-token is processed once, weighted by frequency."""
        words = Counter(PRETOKENIZE.findall(text))
        seqs = {w: list(w.encode("utf-8")) for w in words}
        merges = []
        for new_id in range(256, vocab_size - len(SPECIALS)):
            pairs = Counter()
            for w, count in words.items():
                s = seqs[w]
                for pair in zip(s, s[1:]):
                    pairs[pair] += count
            if not pairs:
                break  # every word is already a single token
            best = max(pairs, key=pairs.get)
            merges.append(best)
            for w in words:
                if len(seqs[w]) > 1:
                    seqs[w] = merge_pair(seqs[w], best, new_id)
            if verbose and len(merges) <= verbose:
                tok = BPETokenizer(merges)
                print(f"   merge {len(merges):3d}: {tok.vocab[best[0]]!r:>10} + {tok.vocab[best[1]]!r:<10}"
                      f" -> {tok.vocab[new_id]!r:<14} (seen {pairs[best]:,}x)")
        return BPETokenizer(merges)

    def _encode_chunk(self, chunk):
        if chunk in self._cache:
            return self._cache[chunk]
        ids = list(chunk.encode("utf-8"))
        while len(ids) >= 2:  # apply the earliest-learned merge first, exactly as in training
            pair = min(zip(ids, ids[1:]), key=lambda p: self.ranks.get(p, float("inf")))
            if pair not in self.ranks:
                break
            ids = merge_pair(ids, pair, 256 + self.ranks[pair])
        self._cache[chunk] = ids
        return ids

    def encode(self, text):
        ids = []
        for part in self._split.split(text):  # special tokens are matched literally, never merged
            if part in self.special_ids:
                ids.append(self.special_ids[part])
            elif part:
                for chunk in PRETOKENIZE.findall(part):
                    ids.extend(self._encode_chunk(chunk))
        return ids

    def decode(self, ids):
        out, buf = [], b""
        for i in ids:
            if i in self.id_to_special:
                out.append(buf.decode("utf-8", errors="replace") + self.id_to_special[i])
                buf = b""
            else:
                buf += self.vocab[i]
        return "".join(out) + buf.decode("utf-8", errors="replace")


# =====================================================================================
# 3. MODEL - a GPT-style decoder: pre-norm (RMSNorm), RoPE, causal SDPA, SwiGLU, tied embeddings.
# =====================================================================================

@dataclass
class Config:
    vocab_size: int = 512
    n_layer: int = 4
    n_head: int = 4
    d_model: int = 128
    ctx: int = 128
    rope_base: float = 10000.0

    @property
    def d_ff(self):  # SwiGLU uses 3 matrices, so ~8/3*d keeps the parameter count of a 4*d GELU MLP
        return 32 * math.ceil(8 * self.d_model / 3 / 32)


class RMSNorm(nn.Module):  # torch>=2.4 has nn.RMSNorm; written out here for torch 2.1
    def __init__(self, d, eps=1e-6):
        super().__init__()
        self.eps, self.weight = eps, nn.Parameter(torch.ones(d))

    def forward(self, x):
        return self.weight * x * torch.rsqrt(x.pow(2).mean(-1, keepdim=True) + self.eps)


def rope_tables(head_dim, ctx, base):
    inv_freq = 1.0 / base ** (torch.arange(0, head_dim, 2).float() / head_dim)
    angles = torch.outer(torch.arange(ctx).float(), inv_freq)  # [ctx, head_dim/2]
    return angles.cos(), angles.sin()


def apply_rope(x, cos, sin):
    """Rotate each (x1, x2) pair of channels by a position-dependent angle. x: [B, H, T, hd]."""
    x1, x2 = x.chunk(2, dim=-1)
    return torch.cat([x1 * cos - x2 * sin, x1 * sin + x2 * cos], dim=-1)


class KVCache:
    """Pre-allocated per-layer K/V buffers [B, H, ctx, hd] plus a write pointer."""

    def __init__(self, batch, n_head, ctx, head_dim):
        self.k = torch.zeros(batch, n_head, ctx, head_dim)
        self.v = torch.zeros(batch, n_head, ctx, head_dim)
        self.pos = 0

    def update(self, k, v):
        T = k.shape[2]
        # This minimal cache supports "prefill from empty" and "decode 1 token". Chunked prefill on
        # top of an existing cache would need an explicit mask (is_causal assumes square T x T).
        assert T == 1 or self.pos == 0, "chunked prefill not supported in this minimal cache"
        self.k[:, :, self.pos:self.pos + T] = k
        self.v[:, :, self.pos:self.pos + T] = v
        self.pos += T
        return self.k[:, :, :self.pos], self.v[:, :, :self.pos]


class Attention(nn.Module):
    def __init__(self, cfg):
        super().__init__()
        self.n_head, self.head_dim = cfg.n_head, cfg.d_model // cfg.n_head
        self.qkv = nn.Linear(cfg.d_model, 3 * cfg.d_model, bias=False)  # one fused GEMM for Q, K, V
        self.proj = nn.Linear(cfg.d_model, cfg.d_model, bias=False)

    def forward(self, x, cos, sin, cache=None):
        B, T, C = x.shape
        q, k, v = self.qkv(x).split(C, dim=2)
        q, k, v = (t.view(B, T, self.n_head, self.head_dim).transpose(1, 2) for t in (q, k, v))
        q, k = apply_rope(q, cos, sin), apply_rope(k, cos, sin)
        if cache is not None:
            k, v = cache.update(k, v)  # all keys/values so far, including this step's
        # T > 1: training or prefill, so mask the future. T == 1: one new query may see every cached key.
        y = F.scaled_dot_product_attention(q, k, v, is_causal=T > 1)
        return self.proj(y.transpose(1, 2).reshape(B, T, C))


class SwiGLU(nn.Module):
    def __init__(self, cfg):
        super().__init__()
        self.gate = nn.Linear(cfg.d_model, cfg.d_ff, bias=False)
        self.up = nn.Linear(cfg.d_model, cfg.d_ff, bias=False)
        self.down = nn.Linear(cfg.d_ff, cfg.d_model, bias=False)

    def forward(self, x):
        return self.down(F.silu(self.gate(x)) * self.up(x))


class Block(nn.Module):
    def __init__(self, cfg):
        super().__init__()
        self.norm1, self.attn = RMSNorm(cfg.d_model), Attention(cfg)
        self.norm2, self.mlp = RMSNorm(cfg.d_model), SwiGLU(cfg)

    def forward(self, x, cos, sin, cache=None):
        x = x + self.attn(self.norm1(x), cos, sin, cache)  # pre-norm: normalize the branch input,
        return x + self.mlp(self.norm2(x))                 # keep the residual stream untouched


class GPT(nn.Module):
    def __init__(self, cfg):
        super().__init__()
        self.cfg = cfg
        self.tok_emb = nn.Embedding(cfg.vocab_size, cfg.d_model)
        self.blocks = nn.ModuleList(Block(cfg) for _ in range(cfg.n_layer))
        self.norm = RMSNorm(cfg.d_model)
        self.lm_head = nn.Linear(cfg.d_model, cfg.vocab_size, bias=False)
        self.lm_head.weight = self.tok_emb.weight  # tied embeddings: one [V, d] matrix, used twice
        cos, sin = rope_tables(cfg.d_model // cfg.n_head, cfg.ctx, cfg.rope_base)
        self.register_buffer("cos", cos, persistent=False)
        self.register_buffer("sin", sin, persistent=False)
        self.apply(self._init)
        for name, p in self.named_parameters():  # scale residual-branch outputs by depth (GPT-2)
            if name.endswith(("attn.proj.weight", "mlp.down.weight")):
                nn.init.normal_(p, std=0.02 / math.sqrt(2 * cfg.n_layer))

    @staticmethod
    def _init(m):
        if isinstance(m, (nn.Linear, nn.Embedding)):
            nn.init.normal_(m.weight, std=0.02)

    def num_params(self):
        return sum(p.numel() for p in self.parameters())  # parameters() de-duplicates the tied matrix

    def new_kv_cache(self, batch=1):
        c = self.cfg
        return [KVCache(batch, c.n_head, c.ctx, c.d_model // c.n_head) for _ in range(c.n_layer)]

    def forward(self, idx, targets=None, caches=None):
        T = idx.shape[1]
        start = 0 if caches is None else caches[0].pos  # absolute position of the first new token
        assert start + T <= self.cfg.ctx, "sequence longer than the context window"
        cos, sin = self.cos[start:start + T], self.sin[start:start + T]
        x = self.tok_emb(idx)
        for i, block in enumerate(self.blocks):
            x = block(x, cos, sin, None if caches is None else caches[i])
        logits = self.lm_head(self.norm(x))
        loss = None
        if targets is not None:
            loss = F.cross_entropy(logits.view(-1, logits.size(-1)), targets.view(-1), ignore_index=-100)
        return logits, loss


# =====================================================================================
# 4. PRETRAINING - next-token prediction with AdamW, warmup + cosine LR, gradient clipping.
# =====================================================================================

def build_dataset(tok, docs):
    eot = tok.special_ids["<|endoftext|>"]
    split = int(0.9 * len(docs))  # hold out whole documents for validation
    enc = lambda ds: torch.tensor([t for d in ds for t in tok.encode(d) + [eot]], dtype=torch.long)
    return enc(docs[:split]), enc(docs[split:])


def get_batch(data, batch_size, ctx, gen):
    ix = torch.randint(len(data) - ctx - 1, (batch_size,), generator=gen)
    x = torch.stack([data[i:i + ctx] for i in ix])
    y = torch.stack([data[i + 1:i + ctx + 1] for i in ix])  # targets = inputs shifted by one
    return x, y


@torch.no_grad()
def estimate_loss(model, data, cfg, batch_size, iters=8):
    model.eval()
    gen = torch.Generator().manual_seed(123)  # same batches every time -> comparable numbers
    loss = sum(model(*get_batch(data, batch_size, cfg.ctx, gen))[1].item() for _ in range(iters)) / iters
    model.train()
    return loss


def lr_at(step, max_steps, peak, warmup):
    if step < warmup:
        return peak * (step + 1) / warmup
    progress = (step - warmup) / max(1, max_steps - warmup)
    return peak * (0.1 + 0.9 * 0.5 * (1 + math.cos(math.pi * progress)))  # cosine down to 10% of peak


def train(args, tok, docs):
    torch.manual_seed(1337)
    cfg = Config(vocab_size=tok.vocab_size)
    model = GPT(cfg)
    train_data, val_data = build_dataset(tok, docs)
    batch_size = 32
    print(f"model: {model.num_params() / 1e6:.2f}M params  d={cfg.d_model} layers={cfg.n_layer} "
          f"heads={cfg.n_head} ctx={cfg.ctx} vocab={cfg.vocab_size}")
    print(f"data : {len(train_data):,} train tokens, {len(val_data):,} val tokens; "
          f"{batch_size * cfg.ctx:,} tokens/step x {args.steps} steps = "
          f"{batch_size * cfg.ctx * args.steps / len(train_data):.1f} epochs")
    decay = [p for p in model.parameters() if p.dim() >= 2]      # matrices get weight decay,
    no_decay = [p for p in model.parameters() if p.dim() < 2]    # norm gains do not
    opt = torch.optim.AdamW([{"params": decay, "weight_decay": 0.1}, {"params": no_decay, "weight_decay": 0.0}],
                            lr=3e-3, betas=(0.9, 0.95))
    gen = torch.Generator().manual_seed(0)
    val0 = estimate_loss(model, val_data, cfg, batch_size)
    log = [(0, val0, val0, 0.0)]  # (step, train batch loss, val loss or None, seconds)
    print(f"step    0  val {val0:.3f}   (a uniform guess over V tokens scores ln V = {math.log(cfg.vocab_size):.3f})")
    t0 = time.time()
    for step in range(args.steps):
        for g in opt.param_groups:
            g["lr"] = lr_at(step, args.steps, peak=3e-3, warmup=30)
        x, y = get_batch(train_data, batch_size, cfg.ctx, gen)
        _, loss = model(x, y)
        opt.zero_grad(set_to_none=True)
        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
        opt.step()
        s = step + 1
        if s % 50 == 0 or s == args.steps:
            el = time.time() - t0
            va = estimate_loss(model, val_data, cfg, batch_size)
            log.append((s, loss.item(), va, el))
            print(f"step {s:4d}  train {loss.item():.3f}  val {va:.3f}  {el:5.0f}s  "
                  f"{s * batch_size * cfg.ctx / el:,.0f} tok/s")
        elif s % 10 == 0:
            log.append((s, loss.item(), None, time.time() - t0))
    train_s = time.time() - t0
    flops = 6 * model.num_params() * batch_size * cfg.ctx * args.steps
    print(f"trained {args.steps} steps in {train_s:.0f}s  (~{flops / 1e12:.2f} TFLOP by the 6*N*D rule)")
    os.makedirs(args.out, exist_ok=True)
    with open(os.path.join(args.out, "loss.csv"), "w") as f:
        f.write("step,train_loss,val_loss,seconds\n")
        f.writelines(f"{s},{a:.4f},{'' if b is None else f'{b:.4f}'},{t:.1f}\n" for s, a, b, t in log)
    torch.save({"cfg": asdict(cfg), "model": model.state_dict(), "merges": tok.merges}, os.path.join(args.out, "base.pt"))
    ascii_plot([r[0] for r in log], [r[1] for r in log])
    print(f"wrote {args.out}/base.pt and {args.out}/loss.csv")
    return model


def ascii_plot(xs, ys, width=60, height=12):
    lo, hi = min(ys), max(ys)
    grid = [[" "] * width for _ in range(height)]
    for x, y in zip(xs, ys):
        c = round(x / max(xs) * (width - 1))
        r = round((hi - y) / (hi - lo + 1e-9) * (height - 1))
        grid[r][c] = "*"
    print("train loss (per batch)")
    for r, row in enumerate(grid):
        label = f"{hi - r * (hi - lo) / (height - 1):5.2f} |" if r % 3 == 0 or r == height - 1 else "      |"
        print(label + "".join(row))
    print("      +" + "-" * width + f"\n       0{'step':^{width - 8}}{max(xs)}")


def load(args):
    ckpt = torch.load(os.path.join(args.out, "base.pt"), map_location="cpu")
    tok = BPETokenizer(ckpt["merges"])
    model = GPT(Config(**ckpt["cfg"]))
    model.load_state_dict(ckpt["model"])
    model.eval()
    return tok, model


# =====================================================================================
# 5. SAMPLING - turn logits into a token: greedy, temperature, top-k, top-p (nucleus).
# =====================================================================================

def sample_next(logits, temperature=1.0, top_k=None, top_p=None, gen=None):
    """logits: [B, V] for the last position. Returns [B, 1] token ids."""
    if temperature == 0:
        return logits.argmax(-1, keepdim=True)            # greedy
    logits = logits / temperature                          # <1 sharpens, >1 flattens
    if top_k is not None:
        kth = torch.topk(logits, min(top_k, logits.size(-1))).values[..., -1:]
        logits = logits.masked_fill(logits < kth, float("-inf"))  # keep the k most likely
    probs = F.softmax(logits, dim=-1)
    if top_p is not None and top_p < 1.0:
        p_sorted, idx_sorted = probs.sort(-1, descending=True)
        outside = p_sorted.cumsum(-1) - p_sorted >= top_p   # mass *before* this token already >= top_p
        p_sorted = p_sorted.masked_fill(outside, 0.0)
        choice = torch.multinomial(p_sorted / p_sorted.sum(-1, keepdim=True), 1, generator=gen)
        return idx_sorted.gather(-1, choice)
    return torch.multinomial(probs, 1, generator=gen)


@torch.no_grad()
def generate(model, prompt_ids, max_new, temperature=0.0, top_k=None, top_p=None,
             use_cache=True, stop_id=None, seed=0):
    model.eval()
    gen = torch.Generator().manual_seed(seed)
    idx = torch.tensor([prompt_ids], dtype=torch.long)
    max_new = min(max_new, model.cfg.ctx - idx.shape[1])
    caches = model.new_kv_cache(1) if use_cache else None
    logits, _ = model(idx, caches=caches)                  # prefill: the whole prompt in one pass
    out = []
    for _ in range(max_new):
        nxt = sample_next(logits[:, -1], temperature, top_k, top_p, gen)
        out.append(nxt.item())
        if out[-1] == stop_id or len(out) == max_new:
            break
        idx = torch.cat([idx, nxt], dim=1)
        # decode: with a cache feed ONE token; without, re-run the whole sequence
        logits, _ = model(nxt if use_cache else idx, caches=caches)
    return out


def cmd_sample(args):
    tok, model = load(args)
    prompt = "One morning, Mira"
    ids = tok.encode(prompt)
    print(f"prompt: {prompt!r}  ->  {len(ids)} tokens {ids}")
    for name, kw in [("greedy (T=0)", dict(temperature=0.0)),
                     ("T=0.8, top-k=20", dict(temperature=0.8, top_k=20)),
                     ("T=1.0, top-p=0.9", dict(temperature=1.0, top_p=0.9)),
                     ("T=2.0 (too hot)", dict(temperature=2.0))]:
        out = generate(model, ids, 60, seed=1, **kw)
        text = tok.decode(out).split("<|endoftext|>")[0]
        print(f"\n[{name}]\n{prompt}{text}")
    print()
    for name in ["Mira", "Tomas", "Lena"]:
        prompt = f"{name} lives in"
        completion = tok.decode(generate(model, tok.encode(prompt), 4)).split(".")[0]
        print(f"fact recall (greedy): {prompt!r} -> {completion!r}")


# =====================================================================================
# 6. KV CACHE - decoding with cached K/V must give the same logits as a full forward pass.
# =====================================================================================

@torch.no_grad()
def cmd_kvcache(args):
    tok, model = load(args)
    cfg = model.cfg
    text = make_corpus(50, seed=7)
    ids = tok.encode(" ".join(text))[:cfg.ctx]
    idx = torch.tensor([ids])
    full, _ = model(idx)                                   # [1, T, V], one causal pass
    caches = model.new_kv_cache(1)
    prefill = 16
    steps = [model(idx[:, :prefill], caches=caches)[0]]   # prefill the first 16 tokens
    for t in range(prefill, idx.shape[1]):                 # then decode one token at a time
        steps.append(model(idx[:, t:t + 1], caches=caches)[0])
    inc = torch.cat(steps, dim=1)
    diff = (full - inc).abs().max().item()
    print(f"logits: full forward vs prefill({prefill}) + {idx.shape[1] - prefill} cached decode steps: "
          f"max |diff| = {diff:.2e}")
    assert torch.allclose(full, inc, atol=1e-4), "KV-cache decode does not match the full forward"

    prompt = tok.encode("On a sunny morning, Felix")
    n_new = cfg.ctx - len(prompt)
    t0 = time.time(); a = generate(model, prompt, n_new, use_cache=False); t_full = time.time() - t0
    t0 = time.time(); b = generate(model, prompt, n_new, use_cache=True); t_kv = time.time() - t0
    assert a == b, "greedy generation differs with and without the cache"
    print(f"greedy generation of {len(a)} tokens is identical with and without the cache")
    print(f"  no cache: {len(a) / t_full:7.1f} tok/s   (re-runs all T tokens every step: O(T^2) total work)")
    print(f"  KV cache: {len(b) / t_kv:7.1f} tok/s   (one new token per step:          O(T)   total work)")
    kv_bytes = 2 * cfg.n_layer * cfg.ctx * cfg.d_model * 4
    print(f"KV cache size = 2 (K,V) x {cfg.n_layer} layers x {cfg.ctx} positions x {cfg.d_model} dims x 4 B "
          f"= {kv_bytes / 1024:.0f} KiB per sequence (fp32)")
    print("PASS: KV-cache decode matches the full forward")


# =====================================================================================
# 7. SFT - teach the *format* "<|user|>question<|assistant|>answer<|end|>" on a handful of
#    pairs. Loss only on the answer tokens. Knowledge must come from pretraining: we test
#    on people whose questions never appear in the SFT set.
# =====================================================================================

def qa_pairs(people):
    return [(q.format(**person(p)), a.format(**person(p))) for p in people for q, a in QUESTIONS]


def sft_example(tok, q, a):
    # Leading spaces matter: in pretraining, words mid-sentence are " Ada", not "Ada" (a different token).
    prompt = tok.encode(f"<|user|> {q}<|assistant|>")
    answer = tok.encode(f" {a}<|end|>")
    ids = prompt + answer
    labels = [-100] * len(prompt) + answer           # -100 = ignored by cross_entropy
    return ids[:-1], labels[1:]                     # shift: predict token t+1 from tokens <= t


def answer(model, tok, q):
    out = generate(model, tok.encode(f"<|user|> {q}<|assistant|>"), 24, stop_id=tok.special_ids["<|end|>"])
    return tok.decode(out).replace("<|end|>", "").strip()


def evaluate_qa(model, tok, pairs, show_every=0):
    hits = 0
    for i, (q, a) in enumerate(pairs):
        got = answer(model, tok, q)
        hits += got == a
        if show_every and i % show_every == 0:
            print(f"   Q: {q:<36} -> {got[:60]!r}  {'OK' if got == a else 'expected ' + repr(a)}")
    return hits / len(pairs)


def warm_start_special_tokens(model, tok):
    """The chat-template tokens never appeared in pretraining, so their embeddings are untrained.
    Copy the embedding of a token that plays the same role in the corpus: <|assistant|> acts like
    the "?" that ends a question (an answer follows), <|user|> and <|end|> like the document
    boundary. (Embeddings are tied, so this also sets their output rows.)"""
    with torch.no_grad():
        E, sp = model.tok_emb.weight, tok.special_ids
        E[sp["<|assistant|>"]] = E[tok.encode("?")[0]]
        E[sp["<|user|>"]] = E[sp["<|endoftext|>"]]
        E[sp["<|end|>"]] = E[sp["<|endoftext|>"]]


def cmd_sft(args):
    tok, model = load(args)
    train_pairs, heldout_pairs = qa_pairs(PEOPLE[:6]), qa_pairs(PEOPLE[6:])
    print(f"{len(train_pairs)} SFT pairs (people 1-6); {len(heldout_pairs)} held-out questions (people 7-12)")
    x, y = sft_example(tok, *train_pairs[0])
    print("loss mask for one example (^ = trained on):")
    print("   " + "".join(tok.decode([t]) for t in x))
    print("   " + "".join(("^" if l != -100 else " ") * len(tok.decode([t])) for t, l in zip(x, y)))

    q = heldout_pairs[0][0]
    print(f"base model, plain text prompt {q!r} -> {tok.decode(generate(model, tok.encode(q), 12))!r}")
    print("   (the knowledge is already there from pretraining; it just never stops)")
    if not args.cold_start:
        warm_start_special_tokens(model, tok)
    print("before SFT, chat template (held-out):")
    before = evaluate_qa(model, tok, heldout_pairs, show_every=12)
    examples = [sft_example(tok, q, a) for q, a in train_pairs]
    T = max(len(x) for x, _ in examples)
    pad = tok.special_ids["<|end|>"]
    X = torch.tensor([x + [pad] * (T - len(x)) for x, _ in examples])
    Y = torch.tensor([y + [-100] * (T - len(y)) for _, y in examples])
    model.train()
    opt = torch.optim.AdamW(model.parameters(), lr=3e-4, weight_decay=0.0)
    t0 = time.time()
    for step in range(args.sft_steps):
        _, loss = model(X, Y)                          # full batch: all 24 pairs every step
        opt.zero_grad(set_to_none=True)
        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
        opt.step()
        if (step + 1) % 10 == 0:
            print(f"   sft step {step + 1:3d}  loss {loss.item():.3f}")
    print(f"SFT: {args.sft_steps} steps in {time.time() - t0:.1f}s")
    print("after SFT (held-out people, never seen in SFT):")
    after = evaluate_qa(model, tok, heldout_pairs, show_every=5)
    train_acc = evaluate_qa(model, tok, train_pairs)
    print(f"exact-match accuracy  held-out: {before:.0%} -> {after:.0%}   SFT pairs: {train_acc:.0%}")
    torch.save({"cfg": asdict(model.cfg), "model": model.state_dict(), "merges": tok.merges},
               os.path.join(args.out, "sft.pt"))


