"""
Build an LLM from scratch: tokenizer -> GPT -> pretraining -> sampling -> KV cache -> SFT.

Everything runs on a laptop CPU in a few minutes with torch>=2.1 and no downloads:
the training text is generated by this file (a tiny made-up world, written for this repo).

    python build_llm.py all          # every step below, in order
    python build_llm.py data         # 1. print a sample of the generated corpus
    python build_llm.py tokenizer    # 2. train the byte-level BPE + round-trip test
    python build_llm.py train        # 3-4. pretrain the tiny GPT -> out/base.pt, out/loss.csv
    python build_llm.py sample       # 5. greedy / temperature / top-k / top-p sampling
    python build_llm.py kvcache      # 6. KV-cache decode == full forward test + speed
    python build_llm.py sft          # 7. supervised fine-tuning on a handful of instruction pairs

Options: --steps N (default 600), --threads N (limit CPU threads), --out DIR (default ./out),
         --sft-steps N (default 30), --cold-start (SFT without warm-starting the chat-template tokens)
"""

