def cmd_tokenizer(args, verbose=10):
    docs = make_corpus()
    t0 = time.time()
    tok = BPETokenizer.train("\n".join(docs), args.vocab, verbose=verbose)
    print(f"trained {len(tok.merges)} merges in {time.time() - t0:.1f}s -> vocab {tok.vocab_size} "
          f"(256 bytes + {len(tok.merges)} merges + {len(SPECIALS)} specials)")
    sample = docs[0]
    ids = tok.encode(sample)
    print(f"{len(sample.encode())} bytes -> {len(ids)} tokens: " + "|".join(tok.decode([i]) for i in ids[:24]) + "|...")
    tests = docs[:200] + ["Café ☕, naïve résumé, 東京, emoji 🙂, tabs\tand\nnewlines", "<|user|>hi<|assistant|>ok<|end|>"]
    for s in tests:
        assert tok.decode(tok.encode(s)) == s, f"round-trip failed for {s!r}"
    unseen = tok.encode(tests[-2])
    print(f"round-trip OK on {len(tests)} strings, incl. unseen unicode ({len(unseen)} tokens, mostly raw bytes)")
    total = sum(len(tok.encode(d)) for d in docs)
    print(f"compression: {sum(len(d.encode()) for d in docs) / total:.2f} bytes/token on the corpus")
    return tok, docs


