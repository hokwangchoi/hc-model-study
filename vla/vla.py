def pi0_cost(n_cams: int = 3, img_tokens: int = 256, text_tokens: int = 48,
             vision_params: float = 400e6, d_vlm: int = 2048, mlp_vlm: int = 16384,
             d_act: int = 1024, mlp_act: int = 4096, n_layers: int = 18, n_heads: int = 8,
             n_kv_heads: int = 1, head_dim: int = 256, horizon: int = 50, n_steps: int = 10,
             mlp_mats: int = 3, bytes_per_param: float = 2.0,
             bw_gbs: float = 204.8, tflops: float = 42.5) -> Dict[str, float]:
    """Analytic cost of ONE action chunk (defaults: pi0 = SigLIP-So400m + Gemma-2B +
    Gemma-300M expert, 3 cameras). FLOPs ~ 2 x params x tokens for every linear layer
    plus 4 x Tq x Tk x (heads*head_dim) per layer for attention. Embedding tables
    are excluded. Time floors are max(FLOPs / peak, bytes / bandwidth) per phase."""
    hq, hkv = n_heads * head_dim, n_kv_heads * head_dim
    p_vlm_layer = d_vlm * hq + 2 * d_vlm * hkv + hq * d_vlm + mlp_mats * d_vlm * mlp_vlm
    p_act_layer = d_act * hq + 2 * d_act * hkv + hq * d_act + mlp_mats * d_act * mlp_act
    P_llm, P_act = n_layers * p_vlm_layer, n_layers * p_act_layer
    T_img = n_cams * img_tokens
    T_p, T_s = T_img + text_tokens, 1 + horizon

    vision_flops = 2 * vision_params * T_img
    prefix_flops = 2 * P_llm * T_p + n_layers * 4 * T_p * T_p * hq
    step_flops = 2 * P_act * T_s + n_layers * 4 * T_s * (T_p + T_s) * hq
    kv_cache_bytes = n_layers * 2 * T_p * hkv * bytes_per_param
    prefix_bytes = (vision_params + P_llm) * bytes_per_param + kv_cache_bytes
    step_bytes = P_act * bytes_per_param + kv_cache_bytes

    peak, bw = tflops * 1e12, bw_gbs * 1e9
    t_prefix = max((vision_flops + prefix_flops) / peak, prefix_bytes / bw)
    t_step = max(step_flops / peak, step_bytes / bw)
    return {
        "T_prefix": T_p, "T_suffix": T_s,
        "params_llm": P_llm, "params_expert": P_act,
        "params_total": vision_params + P_llm + P_act,
        "vision_flops": vision_flops, "prefix_flops": prefix_flops,
        "step_flops": step_flops, "expert_flops": n_steps * step_flops,
        "total_flops": vision_flops + prefix_flops + n_steps * step_flops,
        "kv_cache_bytes": kv_cache_bytes, "prefix_bytes": prefix_bytes, "step_bytes": step_bytes,
        "prefix_intensity": (vision_flops + prefix_flops) / prefix_bytes,
        "step_intensity": step_flops / step_bytes,
        "ridge": peak / bw,
        "t_prefix_ms": 1e3 * t_prefix, "t_step_ms": 1e3 * t_step,
        "t_total_ms": 1e3 * (t_prefix + n_steps * t_step),
        "no_cache_total_ms": 1e3 * n_steps * (t_prefix + t_step),
    }


def print_model_summary(model: Pi0, name: str):
    vis = count_parameters(model.vision)
    tok = model.tok_embed.weight.numel()
    vlm = sum(count_parameters(l.vlm) for l in model.layers)
    act = sum(count_parameters(l.act) for l in model.layers)
    act_io = sum(count_parameters(m) for m in (model.state_proj, model.action_in,
                                                 model.action_time_mlp_in, model.action_time_mlp_out,
                                                 model.norm_out, model.action_out)) + model.suffix_pos.numel()
    total = count_parameters(model)
    print("=" * 64)
    print(f"{name}: pi0-style VLA ({len(model.layers)} shared-attention layers)")
    print("=" * 64)
    print(f"Vision encoder (stub SigLIP):     {vis:>12,}")
    print(f"Token embedding table:            {tok:>12,}")
    print(f"VLM weights in the {len(model.layers)} layers:      {vlm:>12,}")
    print(f"Action-expert weights in layers:  {act:>12,}")
    print(f"Action expert in/out + time MLP:  {act_io:>12,}")
    print("-" * 64)
    print(f"Total:                            {total:>12,}  ({total / 1e6:.2f}M)")
    print(f"horizon H = {model.horizon}, action_dim = {model.action_dim}")


