class Pi0(nn.Module):
    def __init__(
        self,
        img_size: int = 224, patch_size: int = 14, n_cams_max: int = 3,
        vision_depth: int = 2, vocab_size: int = 32000, max_text_len: int = 48,
        d_vlm: int = 256, d_action: int = 128, n_layers: int = 4,
        n_heads: int = 4, n_kv_heads: int = 1, head_dim: int = 64,
        state_dim: int = 14, action_dim: int = 14, horizon: int = 50,
    ):
        super().__init__()
        self.horizon, self.action_dim, self.state_dim = horizon, action_dim, state_dim
        self.d_action = d_action

        # Prefix side (VLM): image tokens + text tokens
        self.vision = VisionEncoder(img_size, patch_size, d_vlm, vision_depth, n_heads)
        self.tok_embed = nn.Embedding(vocab_size, d_vlm)
        max_prefix = n_cams_max * self.vision.n_patches + max_text_len
        self.prefix_pos = nn.Parameter(torch.zeros(1, max_prefix, d_vlm))
        nn.init.trunc_normal_(self.prefix_pos, std=0.02)

        # Suffix side (action expert): state token + H action tokens
        self.state_proj = nn.Linear(state_dim, d_action)
        self.action_in = nn.Linear(action_dim, d_action)
        self.action_time_mlp_in = nn.Linear(2 * d_action, d_action)   # pi0: MLP(concat(action, time))
        self.action_time_mlp_out = nn.Linear(d_action, d_action)
        self.suffix_pos = nn.Parameter(torch.zeros(1, 1 + horizon, d_action))
        nn.init.trunc_normal_(self.suffix_pos, std=0.02)

        self.layers = nn.ModuleList([MoTLayer(d_vlm, d_action, n_heads, n_kv_heads, head_dim)
                                     for _ in range(n_layers)])
        self.norm_out = nn.LayerNorm(d_action)
        self.action_out = nn.Linear(d_action, action_dim)

    # ---- prefix: run once per observation -------------------------------
    def embed_prefix(self, images, token_ids):
        x = torch.cat([self.vision(images), self.tok_embed(token_ids)], dim=1)
        return x + self.prefix_pos[:, :x.shape[1]]

    def run_prefix(self, images, token_ids) -> List[Tuple[torch.Tensor, torch.Tensor]]:
        """The expensive part. Returns the per-layer KV cache of the prefix."""
        x = self.embed_prefix(images, token_ids)
        cache = []
        for layer in self.layers:
            x, kv = layer.prefix(x)
            cache.append(kv)
        return cache

    # ---- suffix: run once per Euler step ---------------------------------
    def embed_suffix(self, state, x_t, t):
        a = self.action_in(x_t)                                              # [B, H, d_a]
        temb = sinusoidal_time_embedding(t, self.d_action)[:, None].expand_as(a)
        a = self.action_time_mlp_out(F.silu(self.action_time_mlp_in(torch.cat([a, temb], -1))))
        s = self.state_proj(state)[:, None]                                  # [B, 1, d_a]
        return torch.cat([s, a], dim=1) + self.suffix_pos

    def run_suffix(self, state, x_t, t, cache):
        """Velocity prediction for the noisy chunk x_t, reading the cached prefix."""
        y = self.embed_suffix(state, x_t, t)
        mask = suffix_block_mask(self.horizon, y.device)
        for layer, kv in zip(self.layers, cache):
            y = layer.suffix(y, kv, mask)
        return self.action_out(self.norm_out(y[:, 1:]))                      # drop the state token

    def velocity(self, images, token_ids, state, x_t, t):
        return self.run_suffix(state, x_t, t, self.run_prefix(images, token_ids))

    def forward_joint(self, images, token_ids, state, x_t, t):
        """Reference implementation WITHOUT the cache: one attention over the full
        [prefix ; suffix] sequence with the 3-block causal mask, each token using its
        own expert's weights. Must equal velocity() exactly (see the tests)."""
        x = self.embed_prefix(images, token_ids)
        y = self.embed_suffix(state, x_t, t)
        T_p, T_s = x.shape[1], y.shape[1]
        mask = torch.zeros(T_p + T_s, T_p + T_s, dtype=torch.bool, device=x.device)
        mask[:T_p, :T_p] = True                                              # prefix block
        mask[T_p:, :T_p] = True                                              # suffix sees prefix
        mask[T_p:, T_p:] = suffix_block_mask(self.horizon, x.device)
        for layer in self.layers:
            qp, kp, vp = layer.vlm.qkv(x)
            qs, ks, vs = layer.act.qkv(y)
            o = attention(torch.cat([qp, qs], 2), torch.cat([kp, ks], 2),
                          torch.cat([vp, vs], 2), mask)
            x, y = layer.vlm.finish(x, o[:, :, :T_p]), layer.act.finish(y, o[:, :, T_p:])
        return self.action_out(self.norm_out(y[:, 1:]))

    # ---- training ----------------------------------------------------------
    def compute_loss(self, batch: Dict[str, torch.Tensor], time_dist: str = "beta"):
        """Flow-matching loss. batch: images [B,N_cam,3,H,W], token_ids [B,T],
        state [B,state_dim], action [B,H,action_dim]."""
        a = batch["action"]
        B = a.shape[0]
        t = sample_flow_time(B, time_dist).to(a.device)
        eps = torch.randn_like(a)
        tt = t.view(B, 1, 1)
        x_t = (1 - tt) * eps + tt * a                 # straight line from noise (t=0) to data (t=1)
        v_target = a - eps                            # its constant velocity
        v_pred = self.velocity(batch["images"], batch["token_ids"], batch["state"], x_t, t)
        return F.mse_loss(v_pred, v_target)

    # ---- inference ---------------------------------------------------------
    @torch.no_grad()
    def generate_action(self, images, token_ids, state, n_steps: int = 10,
                        noise: Optional[torch.Tensor] = None):
        """Prefix once (KV cache), then n_steps Euler steps of the action expert."""
        B = images.shape[0]
        cache = self.run_prefix(images, token_ids)                         # expensive, ONCE
        x = noise if noise is not None else torch.randn(B, self.horizon, self.action_dim,
                                                        device=images.device)
        dt = 1.0 / n_steps
        for i in range(n_steps):
            t = torch.full((B,), i * dt, device=images.device)
            x = x + self.run_suffix(state, x, t, cache) * dt                 # cheap, n_steps times
        return x


