"""
VLA (Vision-Language-Action) Reference Implementation — pi0-style

A robot policy that takes
    - camera images (one or more views)
    - a language instruction ("put the block in the red bowl")
    - proprioception (the robot's current joint state)
and produces
    - an ACTION CHUNK: H future actions (H = 50 in pi0), generated by flow matching.

Usage:
    python vla.py

Architecture — ONE transformer with TWO sets of weights (pi0, arXiv 2410.24164):

    prefix tokens  [image patches..., text tokens...]  -> VLM weights          (PaliGemma 3B in pi0)
    suffix tokens  [state, a_1 ... a_H (noisy actions + flow time)] -> action-expert weights (300M)

    Every layer runs ONE self-attention over the concatenated sequence with a
    block-causal mask (3 blocks):
        [images + text]  — attend among themselves only
        [state]          — attends to prefix + itself
        [actions]        — attend to prefix + state + all actions (bidirectional)
    So the weights only interact through attention, and the prefix never looks at
    the suffix. That is what makes inference cheap: run the prefix ONCE, cache its
    per-layer keys/values, then run only the small suffix 10 times (Euler steps).

    (This is NOT "cross-attention to the VLM's final output". Each action-expert
    layer attends to the SAME layer's VLM keys/values. pi0's appendix contrasts its
    main model with a smaller baseline whose action expert cross-attends to the
    encoder outputs; GR00T N1 — next module — uses that cross-attention style.)

Flow matching convention used in this file (and in the guide):
    x_t = (1 - t) * eps + t * a,   t = 0 is pure noise, t = 1 is data
    target velocity v = a - eps,   integrate dx/dt = v from t = 0 to 1 (10 Euler steps)
  openpi's code uses the mirrored convention (x_t = t*eps + (1-t)*a, u = eps - a,
  integrate from t = 1 down to 0 with dt = -0.1). Same ODE, time axis flipped:
  t_openpi = 1 - t_here and u_openpi = -v_here.
  Training times are drawn from a Beta(1.5, 1)-based density that favours the
  noisy end (pi0 appendix; also GR00T's code).

Model configs (toy backbones, CPU friendly):
    - VLA-S: d_vlm=256, d_action=128, 4 layers
    - VLA-B: d_vlm=512, d_action=256, 6 layers
  Real pi0: SigLIP-So400m + Gemma-2B (width 2048, 18 layers, 8 query heads,
  1 KV head, head_dim 256) + Gemma-300M action expert (width 1024, same depth and
  heads) = 3.3B. pi0_cost() below models that configuration analytically.

Simplifications:
- Vision encoder is a small ViT stub, not SigLIP; text is a token-embedding table.
- LayerNorm + GELU MLP instead of Gemma's RMSNorm + GeGLU; learned positions
  instead of RoPE.
"""
import math
from typing import Dict, List, Optional, Tuple

import torch
import torch.nn as nn
import torch.nn.functional as F


# ============================================================================
# 1. Vision encoder — stub SigLIP / ViT (bidirectional, per camera)
# ============================================================================

class ViTBlock(nn.Module):
    def __init__(self, d: int, n_heads: int, mlp_ratio: float = 4.0):
        super().__init__()
        self.norm1, self.norm2 = nn.LayerNorm(d), nn.LayerNorm(d)
        self.attn = nn.MultiheadAttention(d, n_heads, batch_first=True)
        self.mlp = nn.Sequential(nn.Linear(d, int(d * mlp_ratio)), nn.GELU(),
                                 nn.Linear(int(d * mlp_ratio), d))

    def forward(self, x):
        h = self.norm1(x)
        x = x + self.attn(h, h, h, need_weights=False)[0]
        return x + self.mlp(self.norm2(x))


class VisionEncoder(nn.Module):
    """images [B, N_cam, 3, H, W] -> tokens [B, N_cam * N_patches, d]. pi0: SigLIP-So400m,
    224x224 images, 14x14 patches -> 256 tokens per image."""
    def __init__(self, img_size: int = 224, patch_size: int = 14, d: int = 256,
                 depth: int = 2, n_heads: int = 4):
        super().__init__()
        self.n_patches = (img_size // patch_size) ** 2
        self.patch_embed = nn.Conv2d(3, d, kernel_size=patch_size, stride=patch_size)
        self.pos_embed = nn.Parameter(torch.zeros(1, self.n_patches, d))
        nn.init.trunc_normal_(self.pos_embed, std=0.02)
        self.blocks = nn.ModuleList([ViTBlock(d, n_heads) for _ in range(depth)])
        self.norm = nn.LayerNorm(d)

    def forward(self, images):
        B, N_cam = images.shape[:2]
        x = self.patch_embed(images.flatten(0, 1)).flatten(2).transpose(1, 2) + self.pos_embed
        for blk in self.blocks:
            x = blk(x)
        return self.norm(x).reshape(B, N_cam * self.n_patches, -1)


# ============================================================================
# 2. Shared attention between two experts ("mixture of transformers")
# ============================================================================

def attention(q, k, v, mask: Optional[torch.Tensor]):
    """q [B, H, Tq, hd]; k, v [B, H_kv, Tk, hd]; mask [Tq, Tk] bool (True = may attend).
    Grouped/multi-query attention: each KV head serves H / H_kv query heads."""
    if k.shape[1] != q.shape[1]:
        rep = q.shape[1] // k.shape[1]
        k, v = k.repeat_interleave(rep, dim=1), v.repeat_interleave(rep, dim=1)
    return F.scaled_dot_product_attention(q, k, v, attn_mask=mask)


class ExpertBlock(nn.Module):
    """One expert's weights for one layer: pre-norm, Q/K/V/O projections, MLP.
    Both experts project into the SAME number of heads and head_dim so their
    tokens can share one attention operation; their widths d can differ."""
    def __init__(self, d: int, n_heads: int, n_kv_heads: int, head_dim: int,
                 mlp_ratio: float = 4.0):
        super().__init__()
        self.n_heads, self.n_kv, self.hd = n_heads, n_kv_heads, head_dim
        self.norm1, self.norm2 = nn.LayerNorm(d), nn.LayerNorm(d)
        self.wq = nn.Linear(d, n_heads * head_dim, bias=False)
        self.wk = nn.Linear(d, n_kv_heads * head_dim, bias=False)
        self.wv = nn.Linear(d, n_kv_heads * head_dim, bias=False)
        self.wo = nn.Linear(n_heads * head_dim, d, bias=False)
        self.mlp = nn.Sequential(nn.Linear(d, int(d * mlp_ratio)), nn.GELU(),
                                 nn.Linear(int(d * mlp_ratio), d))

    def qkv(self, x):
        B, T, _ = x.shape
        h = self.norm1(x)
        q = self.wq(h).view(B, T, self.n_heads, self.hd).transpose(1, 2)
        k = self.wk(h).view(B, T, self.n_kv, self.hd).transpose(1, 2)
        v = self.wv(h).view(B, T, self.n_kv, self.hd).transpose(1, 2)
        return q, k, v

    def finish(self, x, attn_out):
        B, H, T, hd = attn_out.shape
        x = x + self.wo(attn_out.transpose(1, 2).reshape(B, T, H * hd))
        return x + self.mlp(self.norm2(x))


class MoTLayer(nn.Module):
    """One layer of the joint transformer: VLM weights for prefix tokens,
    action-expert weights for suffix tokens, one shared attention."""
    def __init__(self, d_vlm, d_act, n_heads, n_kv_heads, head_dim):
        super().__init__()
        self.vlm = ExpertBlock(d_vlm, n_heads, n_kv_heads, head_dim)
        self.act = ExpertBlock(d_act, n_heads, n_kv_heads, head_dim)

    def prefix(self, x):
        """Prefix tokens see only the prefix (bidirectionally). Returns new x and this
        layer's (K, V) — the KV cache the suffix will read."""
        q, k, v = self.vlm.qkv(x)
        return self.vlm.finish(x, attention(q, k, v, None)), (k, v)

    def suffix(self, y, kv_prefix, suffix_mask):
        """Suffix tokens attend to [cached prefix K/V ; their own K/V]."""
        q, k, v = self.act.qkv(y)
        k_all = torch.cat([kv_prefix[0], k], dim=2)
        v_all = torch.cat([kv_prefix[1], v], dim=2)
        T_p, T_s = kv_prefix[0].shape[2], y.shape[1]
        mask = torch.cat([torch.ones(T_s, T_p, dtype=torch.bool, device=y.device),
                          suffix_mask], dim=1)                     # [T_s, T_p + T_s]
        return self.act.finish(y, attention(q, k_all, v_all, mask))


def suffix_block_mask(horizon: int, device=None) -> torch.Tensor:
    """[1 + H, 1 + H] mask for [state, a_1..a_H]: the state token does not see the
    actions (it is its own block); actions see the state and each other."""
    m = torch.ones(1 + horizon, 1 + horizon, dtype=torch.bool, device=device)
    m[0, 1:] = False
    return m


# ============================================================================
# 3. Flow matching helpers
# ============================================================================

def sinusoidal_time_embedding(t: torch.Tensor, d: int, min_period: float = 4e-3,
                              max_period: float = 4.0) -> torch.Tensor:
    """Sine-cosine embedding of flow time t in [0, 1] (periods between min and max,
    as in openpi's posemb_sincos)."""
    frac = torch.linspace(0.0, 1.0, d // 2, device=t.device)
    period = min_period * (max_period / min_period) ** frac
    ang = t[:, None] * (2 * math.pi / period[None])
    return torch.cat([torch.sin(ang), torch.cos(ang)], dim=-1)


def sample_flow_time(batch: int, dist: str = "beta", s: float = 0.999) -> torch.Tensor:
    """Training flow times in this file's convention (t = 0 noise, t = 1 data).
    'beta':    t = s * (1 - u), u ~ Beta(1.5, 1)  -> more samples near the noisy end
               (pi0 appendix: p(tau) = Beta((s - tau)/s; 1.5, 1), s = 0.999)
    'uniform': t ~ U[0, 1)."""
    if dist == "uniform":
        return torch.rand(batch)
    u = torch.distributions.Beta(1.5, 1.0).sample((batch,))
    return s * (1.0 - u)


def gaussian_mixture_velocity(x: torch.Tensor, t: float, means, std: float,
                              weights=None) -> torch.Tensor:
    """EXACT marginal velocity v(x, t) = E[a - eps | x_t = x] for 1-D data
    a ~ sum_k w_k N(mu_k, std^2), eps ~ N(0, 1), x_t = (1 - t) eps + t a.
    This is what a perfectly trained flow model would predict. The guide's 1-D
    step-through widget uses the identical formula."""
    means = torch.as_tensor(means, dtype=x.dtype)
    K = means.numel()
    w = torch.full((K,), 1.0 / K, dtype=x.dtype) if weights is None else torch.as_tensor(weights, dtype=x.dtype)
    var = (1 - t) ** 2 + (t * std) ** 2                     # Var[x_t | component k]
    xm = x[..., None] - t * means                            # x - E[x_t | k]
    logp = torch.log(w) - 0.5 * xm ** 2 / var
    r = torch.softmax(logp, dim=-1)                          # responsibilities P(k | x_t)
    e_a = means + (t * std ** 2 / var) * xm                  # E[a   | x_t, k]
    e_eps = ((1 - t) / var) * xm                             # E[eps | x_t, k]
    return (r * (e_a - e_eps)).sum(-1)


def euler_integrate(v_fn, noise: torch.Tensor, n_steps: int, return_path: bool = False):
    """x <- x + v(x, t) * dt from t = 0 (noise) to t = 1 (action)."""
    x, dt, path = noise, 1.0 / n_steps, [noise]
    for i in range(n_steps):
        x = x + v_fn(x, i * dt) * dt
        path.append(x)
    return (x, path) if return_path else x


